#include <iostream>
#include <cmath>

using namespace std;

int main() {
    int choice;
    double a, b, result;

    cout << "==========================================" << endl;
    cout << "   МАТЕМАТИКАЛЫҚ КӨМЕКШІ-КАЛЬКУЛЯТОР      " << endl;
    cout << "==========================================" << endl;
    cout << "1. Қосу (+)" << endl;
    cout << "2. Азайту (-)" << endl;
    cout << "3. Көбейту (*)" << endl;
    cout << "4. Бөлу (/)" << endl;
    cout << "Амалды таңдаңыз (1-4): ";
    cin >> choice;

    if (choice == 1) {
        cout << "\n--- ҚОСУ АМАЛЫ ---" << endl;
        cout << "Бірінші санды енгізіңіз: ";
        cin >> a;
        cout << "Екінші санды енгізіңіз: ";
        cin >> b;
        
        result = a + b;
        cout << "\nНәтиже: " << a << " + " << b << " = " << result << endl;
        cout << "Түсіндірме: Екі оң сан қосылғанда олардың шамалары бірігеді." << endl;
    } 
    else if (choice == 2) {
        cout << "\n--- АЗАЙТУ АМАЛЫ ---" << endl;
        cout << "Бірінші санды енгізіңіз: ";
        cin >> a;
        cout << "Екінші санды енгізіңіз: ";
        cin >> b;
        
        result = a - b;
        cout << "\nНәтиже: " << a << " - " << b << " = " << result << endl;
        cout << "Түсіндірме: Азайту — бұл бірінші саннан екінші санның шамасын алып тастау." << endl;
    } 
    else if (choice == 3) {
        cout << "\n--- КӨБЕЙТУ АМАЛЫ ---" << endl;
        cout << "Бірінші санды енгізіңіз: ";
        cin >> a;
        cout << "Екінші санды енгізіңіз: ";
        cin >> b;
        
        result = a * b;
        cout << "\nНәтиже: " << a << " * " << b << " = " << result << endl;
        cout << "Түсіндірме: Көбейту — бірінші санды екінші санның мөлшерінде бірнеше рет қосу." << endl;
    } 
    else if (choice == 4) {
        cout << "\n--- БӨЛУ АМАЛЫ ---" << endl;
        cout << "Бірінші санды енгізіңіз: ";
        cin >> a;
        cout << "Екінші санды енгізіңіз: ";
        cin >> b;
        
        if (b != 0) {
            result = a / b;
            cout << "\nНәтиже: " << a << " / " << b << " = " << result << endl;
            cout << "Түсіндірме: Бөлу — санның ішінде екінші санның қанша рет бар екенін анықтау." << endl;
        } else {
            cout << "\nҚате: Санды 0-ге бөлуге болмайды!" << endl;
        }
    } 
    else {
        cout << "\nҚате таңдау! Тек 1-ден 4-ке дейінгі санды енгізіңіз." << endl;
    }

    return 0;
}
